// Runs after `next build` (static export) to prepare out/ for Cloudflare Pages:
// 1. Localized 404.html per locale (Pages serves the nearest 404.html).
// 2. _redirects that rewrite unknown course/lesson slugs to the client shell.
//    Pages applies _redirects even when a file exists, so every pre-rendered
//    slug gets a self-rewrite placed before the catch-all rule.
import { copyFile, readdir, rm, stat, writeFile } from "node:fs/promises";
import { join } from "node:path";

const OUT_DIR = new URL("../out/", import.meta.url).pathname;
const DEFAULT_LOCALE = "es";
const SHELL = "_";
const ROUTES = {
  es: { courses: "cursos", lessons: "lecciones" },
  en: { courses: "courses", lessons: "lessons" },
};

async function exists(path) {
  try {
    await stat(path);
    return true;
  } catch {
    return false;
  }
}

async function listDirs(path) {
  if (!(await exists(path))) return [];
  const entries = await readdir(path, { withFileTypes: true });
  return entries.filter((e) => e.isDirectory() && e.name !== SHELL).map((e) => e.name);
}

for (const locale of Object.keys(ROUTES)) {
  const source = join(OUT_DIR, locale, "404", "index.html");
  if (!(await exists(source))) {
    throw new Error(`Missing ${source}. Did the [...missing] route change?`);
  }
  await copyFile(source, join(OUT_DIR, locale, "404.html"));
}
await copyFile(join(OUT_DIR, DEFAULT_LOCALE, "404.html"), join(OUT_DIR, "404.html"));
await rm(join(OUT_DIR, "_not-found"), { recursive: true, force: true });

const staticRules = [];
const dynamicRules = [];
for (const [locale, { courses, lessons }] of Object.entries(ROUTES)) {
  const base = `/${locale}/${courses}`;
  for (const slug of await listDirs(join(OUT_DIR, locale, courses))) {
    staticRules.push(`${base}/${slug}/ ${base}/${slug}/ 200`);
  }
  dynamicRules.push(`${base}/:slug/${lessons}/:lesson/ ${base}/${SHELL}/${lessons}/${SHELL}/ 200`);
  dynamicRules.push(`${base}/:slug/ ${base}/${SHELL}/ 200`);
}

await writeFile(
  join(OUT_DIR, "_redirects"),
  ["# Generated by scripts/post-export.mjs", ...staticRules, ...dynamicRules, ""].join("\n"),
);

console.log(`post-export: 404 pages and _redirects written (${staticRules.length} pre-rendered slugs)`);
